import { launch, startRecording, encode, probe, sleep, CLIPS } from './lib.mjs';
const b = await launch();
await b.js("document.querySelector('#name').value='Eren'; document.querySelector('#quick').click(); 1");
await b.waitFor("document.documentElement.classList.contains('in-game')", 90);
await sleep(8000);
const fps = await b.js("new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 3000) requestAnimationFrame(f); else res(n / 3); }; requestAnimationFrame(f); })");
console.log('page rAF fps', fps, 'size', await b.js('innerWidth + "x" + innerHeight + " dpr " + devicePixelRatio'));
const stop = await startRecording(CLIPS + 'probe.mp4');
await sleep(5000);
const raw = await stop();
console.log('raw', probe(raw));
encode(raw, CLIPS + 'probe.mp4');
console.log('mp4', probe(CLIPS + 'probe.mp4'));
b.close();
